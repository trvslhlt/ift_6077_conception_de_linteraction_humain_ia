// Generates the device catalog's openDAW half (page/Catalog.ts) in headless Chromium: opens a new project, creates,
// reads and deletes every device, and writes /out/generated.json. Run via `make catalog`, which mounts catalog/ at /out
// and passes the openDAW commit; regenerate when the openDAW pin changes.
import {writeFileSync} from "node:fs"
import {chromium} from "playwright"

const URL = process.env.URL ?? "http://localhost:8080/"
const browser = await chromium.launch()
const page = await (await browser.newContext({viewport: {width: 1440, height: 900}})).newPage()
try {
    await page.goto(URL, {waitUntil: "networkidle", timeout: 180000})
    await page.getByText("New Project", {exact: true}).click()
    await page.getByText("Add instrument").first().waitFor({timeout: 60000})
    await page.waitForFunction(() => window.takedo !== undefined, null, {timeout: 60000})
    const catalog = await page.evaluate(() => window.takedo.debug.catalog())
    if (catalog === null) {throw new Error("no project open")}
    const out = {
        "//": "Generated by `make catalog` (page/Catalog.ts) from openDAW itself; don't edit by hand. The hand-written half is devices.json, with the same keys.",
        opendaw: process.env.OPENDAW_REF ?? "unknown",
        generated: new Date().toISOString().slice(0, 10),
        devices: Object.fromEntries(catalog.devices.map(device => [device.key, device])),
        failures: catalog.failures
    }
    writeFileSync("/out/generated.json", JSON.stringify(out, null, 2) + "\n")
    const counts = catalog.devices.reduce((sum, device) => sum + device.parameters.length, 0)
    console.log(`${catalog.devices.length} devices (${catalog.devices.filter(device => device.allowed).length} allowed), ${counts} parameters`)
    for (const failure of catalog.failures) {console.log(`failed: ${failure.factory}: ${failure.error}`)}
    process.exitCode = catalog.failures.length === 0 ? 0 : 1
} finally {
    await browser.close()
}
